"""Builds css/theme.css from tools/theme/tokens.json.
Usage (from the project folder):  python tools/theme/build_theme_css.py
convert.py <project> replaces hard-coded on-screen brand colours by var(--c-<hex>) and adds them to tokens.json;
run it only on files that still contain raw colours (it is safe to run again)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(os.path.dirname(here))
used = sorted(json.load(open(os.path.join(here, 'tokens.json'))))
STATUS = {  # fixed status tones — never themed (V266.5, docs/UI_STANDARDS.md)
  'neutral': ('#eef2f6', '#475569'), 'blue': ('#e8f0fb', '#1e4f86'), 'amber': ('#fef3c7', '#92400e'),
  'green': ('#dcfce7', '#166534'), 'red': ('#fee2e2', '#991b1b'), 'purple': ('#ede9fe', '#5b21b6'), 'teal': ('#ccfbf1', '#0f766e'),
}
st = ''.join(f'--st-{k}-bg:{bg};--st-{k}-fg:{fg};' for k, (bg, fg) in STATUS.items())
base = ''.join(f'--c-{h}:#{h};' for h in used)
css = f"""/* BizCore V266.5 — application theme (Administration → System Preferences → Application theme).
   Every on-screen brand colour is a token --c-<hex>, defined here with its original (Corporate Navy) value.
   V271.8.3: another theme is painted by applyTheme() in js/app.js, which works out every token as a plain #hex
   (hue shift / colour strength / lightness lift) — no CSS relative colours, so all browsers show the same. Not themed: status tones (--st-*), neutral greys,
   document identity colours and printed / A4 documents.
   GENERATED by tools/theme/build_theme_css.py — do not edit by hand. */
:root{{--th-h:0;--th-c:1;--th-l:0;{st}{base}}}
"""
open(os.path.join(root, 'css', 'theme.css'), 'w', encoding='utf-8').write(css)
print('theme.css:', len(used), 'tokens,', len(css), 'bytes')
